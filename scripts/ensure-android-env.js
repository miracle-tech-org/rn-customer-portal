/**
 * Prepares Android env before `react-native run-android`.
 * - Locates the Android SDK
 * - Writes android/local.properties (sdk.dir)
 * - Puts platform-tools + emulator on PATH for this process
 * - Fails with a clear message if Android Studio / SDK is missing
 */
const fs = require('fs');
const path = require('path');
const {spawnSync} = require('child_process');

const projectRoot = path.resolve(__dirname, '..');
const androidDir = path.join(projectRoot, 'android');
const localPropertiesPath = path.join(androidDir, 'local.properties');
const isWindows = process.platform === 'win32';

function exists(filePath) {
  try {
    return fs.existsSync(filePath);
  } catch {
    return false;
  }
}

function looksLikeSdk(sdkRoot) {
  if (!sdkRoot) {
    return false;
  }
  return (
    exists(path.join(sdkRoot, 'platform-tools')) ||
    exists(path.join(sdkRoot, 'platforms')) ||
    exists(path.join(sdkRoot, 'build-tools'))
  );
}

function candidateSdkPaths() {
  const home = process.env.USERPROFILE || process.env.HOME || '';
  const localAppData = process.env.LOCALAPPDATA || '';
  const values = [
    process.env.ANDROID_HOME,
    process.env.ANDROID_SDK_ROOT,
    localAppData ? path.join(localAppData, 'Android', 'Sdk') : null,
    home ? path.join(home, 'AppData', 'Local', 'Android', 'Sdk') : null,
    'C:\\Android\\Sdk',
    'C:\\Android\\android-sdk',
    'D:\\Android\\Sdk',
    'E:\\Android\\Sdk',
    home ? path.join(home, 'Android', 'Sdk') : null,
    '/Users/' + path.basename(home || 'user') + '/Library/Android/sdk',
    home ? path.join(home, 'Library', 'Android', 'sdk') : null,
    home ? path.join(home, 'Android', 'Sdk') : null,
  ];

  return [...new Set(values.filter(Boolean))];
}

function findSdk() {
  for (const candidate of candidateSdkPaths()) {
    if (looksLikeSdk(candidate)) {
      return path.resolve(candidate);
    }
  }
  return null;
}

function toGradleSdkDir(sdkRoot) {
  // Gradle on Windows expects escaped backslashes in local.properties
  return sdkRoot.replace(/\\/g, '\\\\');
}

function writeLocalProperties(sdkRoot) {
  const contents = [
    '# Generated by scripts/ensure-android-env.js — do not commit machine-specific paths.',
    `sdk.dir=${toGradleSdkDir(sdkRoot)}`,
    '',
  ].join('\n');

  fs.writeFileSync(localPropertiesPath, contents, 'utf8');
  console.log(`[android-env] Wrote ${path.relative(projectRoot, localPropertiesPath)}`);
  console.log(`[android-env] sdk.dir=${sdkRoot}`);
}

function prependPath(extraDirs) {
  const current = process.env.PATH || '';
  const parts = extraDirs.filter(dir => exists(dir) && !current.includes(dir));
  if (parts.length === 0) {
    return;
  }
  process.env.PATH = [...parts, current].join(path.delimiter);
}

function commandExists(command) {
  const probe = isWindows ? `where ${command}` : `command -v ${command}`;
  const result = spawnSync(probe, {
    shell: true,
    encoding: 'utf8',
  });
  return result.status === 0;
}

function printMissingSdkHelp() {
  console.error(`
[android-env] Android SDK was not found on this PC.

npm run android needs:
  1) Android Studio installed
  2) Android SDK (usually %LOCALAPPDATA%\\Android\\Sdk)
  3) An emulator AVD created in Android Studio, OR a USB phone with USB debugging
  4) ANDROID_HOME set (optional if SDK is in the default location)

On the PC where Android Studio is already installed:
  - Open Android Studio → More Actions → SDK Manager
  - Confirm SDK path, then set a User environment variable:
      ANDROID_HOME = <that SDK path>
  - Add to User PATH:
      %ANDROID_HOME%\\platform-tools
      %ANDROID_HOME%\\emulator
  - Open a NEW terminal and run:
      npm run doctor:android
      npm run android

This PC cannot build/run the Android app until the SDK is installed.
`);
}

function main() {
  const sdkRoot = findSdk();

  if (!sdkRoot) {
    printMissingSdkHelp();
    process.exit(1);
  }

  process.env.ANDROID_HOME = sdkRoot;
  process.env.ANDROID_SDK_ROOT = sdkRoot;

  prependPath([
    path.join(sdkRoot, 'platform-tools'),
    path.join(sdkRoot, 'emulator'),
    path.join(sdkRoot, 'tools'),
    path.join(sdkRoot, 'tools', 'bin'),
  ]);

  writeLocalProperties(sdkRoot);

  if (!commandExists('adb')) {
    console.warn(
      '[android-env] Warning: adb still not on PATH. Install Android SDK Platform-Tools in SDK Manager.',
    );
  } else {
    console.log('[android-env] adb is available');
  }

  const emulatorCheck = spawnSync('emulator -list-avds', {
    shell: true,
    encoding: 'utf8',
  });

  if (emulatorCheck.status === 0) {
    const avds = (emulatorCheck.stdout || '')
      .split(/\r?\n/)
      .map(line => line.trim())
      .filter(Boolean);

    if (avds.length === 0) {
      console.warn(
        '[android-env] No emulators found. Create one in Android Studio (Device Manager), or plug in a phone.',
      );
    } else {
      console.log(`[android-env] Emulators: ${avds.join(', ')}`);
    }
  }
}

main();
